#!/usr/bin/env bash
# Refresh every generated data file, in dependency order, then stamp the
# scrape date the addon shows in its UI.
#
#   sources   must run first: the other scrapers read the season slug and
#             the per-spec page URLs back out of Data/*/sources.lua.
#   archon    must run before wowhead: the Wowhead talent-page parser
#             matches hero talent names harvested from the Archon data.
#
# Usage: tools/refresh_all.sh [--season midnight-season-2]
set -euo pipefail

cd "$(dirname "$0")/.."
SEASON="midnight-season-2"
[[ ${1:-} == "--season" ]] && SEASON="$2"

run() { echo "=== $* ==="; python3 "tools/$@"; }

run refresh_sources.py --wowhead-season "$SEASON"
run refresh_archon.py
run refresh_wowhead.py
run refresh_wowhead_gear.py
run refresh_icyveins.py
run refresh_murlok.py

today=$(date +%F)
printf -- '-- This file is generated by the scraper. Do not edit by hand.\nClassCodex_LastScrape = "%s"\n' "$today" > Data/Generated.lua
echo "=== stamped Data/Generated.lua with $today ==="

if LUAC="${LUAC:-$(command -v luac5.1 || command -v luac || true)}"; [[ -n "$LUAC" ]]; then
    LUAC="$LUAC" tools/check_lua.sh
else
    echo "note: no Lua compiler on PATH, skipping the syntax check" >&2
fi
